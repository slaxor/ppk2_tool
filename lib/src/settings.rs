//! Daemon settings, persisted as TOML under the XDG config dir.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};

use crate::Error;
use crate::cmd::PowerMode;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Settings {
    pub mode: PowerMode,
    /// The voltage wanted at VOUT; what is sent to the regulator goes through the calibration.
    pub millivolts: u16,
    pub fold: u32,
}

/// Measured behaviour of one PPK2's source regulator: output = gain × command + offset_mv.
/// Stored per device in `$XDG_CONFIG_HOME/ppk2_tool/calibration/<serial>.toml`.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct RegulatorCalibration {
    pub gain: f64,
    pub offset_mv: f64,
}

impl Default for RegulatorCalibration {
    fn default() -> Self {
        RegulatorCalibration {
            gain: 1.0,
            offset_mv: 0.0,
        }
    }
}

/// Commands the regulator accepts.
pub const REGULATOR_MV: std::ops::RangeInclusive<u16> = 800..=5000;

impl RegulatorCalibration {
    pub fn path(serial: &str) -> PathBuf {
        config_dir()
            .join("ppk2_tool")
            .join("calibration")
            .join(format!("{serial}.toml"))
    }

    /// The stored calibration of this unit, or none (identity) if it was never calibrated.
    pub fn load(serial: &str) -> Result<Self, Error> {
        let path = Self::path(serial);
        match std::fs::read_to_string(&path) {
            Ok(text) => toml::from_str(&text)
                .map_err(|e| Error::BadSettings(format!("{}: {e}", path.display()))),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Self::default()),
            Err(e) => Err(e.into()),
        }
    }

    pub fn save(&self, serial: &str) -> Result<(), Error> {
        let path = Self::path(serial);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        let text = toml::to_string_pretty(self).map_err(|e| Error::BadSettings(e.to_string()))?;
        std::fs::write(path, text)?;
        Ok(())
    }

    /// Fit a line through two (command, measured) points.
    pub fn from_points(low: (u16, f64), high: (u16, f64)) -> Result<Self, Error> {
        let (c1, m1) = (f64::from(low.0), low.1);
        let (c2, m2) = (f64::from(high.0), high.1);
        if c2 <= c1 {
            return Err(Error::BadSettings("calibration points must differ".into()));
        }
        let gain = (m2 - m1) / (c2 - c1);
        if !(0.9..=1.1).contains(&gain) {
            return Err(Error::BadSettings(format!(
                "regulator gain {gain:.4} is implausible; check the readings"
            )));
        }
        Ok(RegulatorCalibration {
            gain,
            offset_mv: m1 - gain * c1,
        })
    }

    /// What to send to the regulator so that VOUT reads `wanted_mv`.
    pub fn command_for(&self, wanted_mv: u16) -> u16 {
        let raw = (f64::from(wanted_mv) - self.offset_mv) / self.gain;
        let (lo, hi) = (*REGULATOR_MV.start(), *REGULATOR_MV.end());
        raw.round().clamp(f64::from(lo), f64::from(hi)) as u16
    }
}

impl Default for Settings {
    fn default() -> Self {
        Settings {
            mode: PowerMode::Source,
            millivolts: 3300,
            fold: 10,
        }
    }
}

impl Settings {
    /// Written by the daemon and by `calibrate-voltage`.
    pub fn path() -> PathBuf {
        config_dir().join("ppk2_tool").join("settings.toml")
    }

    /// Read-only starting point, e.g. generated by the home-manager module.
    pub fn defaults_path() -> PathBuf {
        config_dir().join("ppk2_tool").join("defaults.toml")
    }

    /// `settings.toml`, else `defaults.toml`, else built-in defaults.
    pub fn load() -> Result<Self, Error> {
        for path in [Self::path(), Self::defaults_path()] {
            match std::fs::read_to_string(&path) {
                Ok(text) => {
                    return toml::from_str(&text)
                        .map_err(|e| Error::BadSettings(format!("{}: {e}", path.display())));
                }
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
                Err(e) => return Err(e.into()),
            }
        }
        Ok(Self::default())
    }

    pub fn save(&self) -> Result<(), Error> {
        let path = Self::path();
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        let text = toml::to_string_pretty(self).map_err(|e| Error::BadSettings(e.to_string()))?;
        std::fs::write(path, text)?;
        Ok(())
    }
}

fn config_dir() -> PathBuf {
    std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
        .unwrap_or_else(|| PathBuf::from("."))
}

/// Where the daemon listens: `$XDG_RUNTIME_DIR/ppk2_tool.sock`, or a per-user path under /tmp.
pub fn socket_path() -> PathBuf {
    let dir = std::env::var_os("XDG_RUNTIME_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| std::env::temp_dir().join(format!("ppk2_tool-{}", whoami())));
    dir.join("ppk2_tool.sock")
}

fn whoami() -> String {
    std::env::var("USER").unwrap_or_else(|_| "user".into())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn settings_round_trip_through_toml() {
        let s = Settings {
            mode: PowerMode::Ampere,
            millivolts: 1800,
            fold: 100,
        };
        let text = toml::to_string(&s).expect("serialises");
        assert_eq!(toml::from_str::<Settings>(&text).expect("parses"), s);
    }

    #[test]
    fn calibration_round_trips_through_toml() {
        let cal = RegulatorCalibration {
            gain: 0.99,
            offset_mv: -1.5,
        };
        let text = toml::to_string(&cal).expect("serialises");
        assert_eq!(
            toml::from_str::<RegulatorCalibration>(&text).expect("parses"),
            cal
        );
    }

    #[test]
    fn calibration_inverts_the_measured_line() {
        let cal = RegulatorCalibration::from_points((1800, 1782.0), (3300, 3267.0))
            .expect("plausible readings");
        assert!((cal.gain - 0.99).abs() < 1e-9, "{cal:?}");
        assert_eq!(cal.command_for(3300), 3333);
        assert_eq!(cal.command_for(1800), 1818);
    }

    #[test]
    fn identity_calibration_passes_values_through() {
        assert_eq!(RegulatorCalibration::default().command_for(3300), 3300);
        assert_eq!(RegulatorCalibration::default().command_for(100), 800);
    }

    #[test]
    fn implausible_readings_are_refused() {
        assert!(RegulatorCalibration::from_points((1800, 1800.0), (3300, 33000.0)).is_err());
        assert!(RegulatorCalibration::from_points((3300, 1.0), (1800, 2.0)).is_err());
    }

    #[test]
    fn missing_keys_fall_back_to_defaults() {
        let s: Settings = toml::from_str("fold = 7\n").expect("partial file parses");
        assert_eq!(s.fold, 7);
        assert_eq!(s.millivolts, 3300);
        assert_eq!(s.mode, PowerMode::Source);
    }
}
